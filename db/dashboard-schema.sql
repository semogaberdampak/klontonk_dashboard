                       'amount', NEW.amount, 'reason', NEW.reason, 'cashier', NEW.cashier));
  RETURN NEW;
END $$;-- Perubahan level platform (clients / tenants / plans / subscriptions).
-- Satu fungsi untuk empat tabel: barisnya kecil, jadi isi penuh disimpan sebagai
-- perbandingan sebelum -> sesudah.
CREATE OR REPLACE FUNCTION public.audit_platform() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_before jsonb;
  v_after  jsonb;
  v_action text;
  v_entity_id text;
  v_client text;
  v_tenant text;
  v_prefix text;
BEGIN
  v_before := CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN to_jsonb(OLD) END;
  v_after  := CASE WHEN TG_OP IN ('INSERT','UPDATE') THEN to_jsonb(NEW) END;

  v_prefix := CASE TG_TABLE_NAME
                WHEN 'clients'       THEN 'client'
                WHEN 'tenants'       THEN 'branch'
                WHEN 'plans'         THEN 'plan'
                WHEN 'subscriptions' THEN 'subscription'
              END;
  v_action := v_prefix || CASE TG_OP WHEN 'INSERT' THEN '.create' WHEN 'UPDATE' THEN '.update' ELSE '.delete' END;

  IF TG_TABLE_NAME = 'clients' THEN
    v_entity_id := COALESCE(v_after->>'id', v_before->>'id');
    v_client := v_entity_id;
  ELSIF TG_TABLE_NAME = 'tenants' THEN
    v_entity_id := COALESCE(v_after->>'id', v_before->>'id');
    v_client := COALESCE(v_after->>'client_id', v_before->>'client_id');
    v_tenant := v_entity_id;
  ELSIF TG_TABLE_NAME = 'plans' THEN
    v_entity_id := COALESCE(v_after->>'code', v_before->>'code');
  ELSE
    v_entity_id := COALESCE(v_after->>'id', v_before->>'id');
    v_client := COALESCE(v_after->>'client_id', v_before->>'client_id');
  END IF;

  IF TG_OP = 'UPDATE' AND v_before = v_after THEN
    RETURN NEW;
  END IF;

  PERFORM public.write_audit(v_action, TG_TABLE_NAME, v_entity_id, v_client, v_tenant,
    jsonb_build_object('sebelum', v_before, 'sesudah', v_after));

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;

