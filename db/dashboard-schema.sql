-- 16. Hapus akun
--     delete_app_user() adalah fungsi milik klontonk_pos dan DIGANTI di sini:
--     versi aslinya hanya memeriksa app_role() = ''admin'' tanpa batas client, sehingga
--     admin client A bisa menghapus akun milik client B. Versi ini menutup celah itu.
--     Bila db/schema.sql POS diubah, sinkronkan kembali bagian ini.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.delete_app_user(p_username text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_target public.profiles%ROWTYPE;
  v_actor_client text;
BEGIN
  IF public.app_role() IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Akses ditolak. Fitur ini hanya untuk Admin.' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO v_target FROM public.profiles WHERE username = lower(btrim(p_username));
  IF NOT FOUND THEN
    RAISE EXCEPTION 'User tidak ditemukan.' USING ERRCODE = 'P0001';
  END IF;

  v_actor_client := public.app_client_id();
  IF v_actor_client IS NULL
     OR public.tenant_client(v_target.tenant_id) IS DISTINCT FROM v_actor_client THEN
    RAISE EXCEPTION 'Akun itu bukan bagian dari client Anda.' USING ERRCODE = '42501';
  END IF;
  IF v_target.id = auth.uid() THEN
    RAISE EXCEPTION 'Tidak bisa menghapus akun Anda sendiri.' USING ERRCODE = 'P0001';
  END IF;
  IF v_target.role = 'admin' AND (
       SELECT count(*) FROM public.profiles p JOIN public.tenants t ON t.id = p.tenant_id
        WHERE p.role = 'admin' AND t.client_id = v_actor_client) <= 1 THEN
    RAISE EXCEPTION 'Minimal harus ada satu Admin di client ini.' USING ERRCODE = 'P0001';
  END IF;

  DELETE FROM auth.users WHERE id = v_target.id;
END $$;

