  expires_at date NOT NULL,
  status     text NOT NULL DEFAULT 'trial' CHECK (status IN ('trial','aktif','jatuh_tempo','berhenti')),
  note       text CHECK (note IS NULL OR char_length(note) <= 200),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT subscriptions_period_ck CHECK (expires_at >= started_at)
);
CREATE INDEX IF NOT EXISTS subscriptions_client_idx ON public.subscriptions (client_id, expires_at DESC);
CREATE INDEX IF NOT EXISTS subscriptions_expires_idx ON public.subscriptions (expires_at);

