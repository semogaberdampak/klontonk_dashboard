CREATE OR REPLACE FUNCTION public.gen_tenant_id() RETURNS text
  LANGUAGE plpgsql VOLATILE SET search_path = ''
AS $$
DECLARE
  v_next bigint := nextval('public.tenants_id_seq');
BEGIN
  IF v_next > 999 THEN
    RAISE EXCEPTION 'Batas 999 cabang (format id T###) tercapai. Perlu migrasi format id di klontonk_pos dan dashboard.' USING ERRCODE = 'P0001';
  END IF;
  RETURN 'T' || lpad(v_next::text, 3, '0');
END $$;

