-- Apakah pemanggil admin platform (vendor)?
CREATE OR REPLACE FUNCTION public.is_superadmin() RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$ SELECT EXISTS (SELECT 1 FROM public.platform_admins a WHERE a.id = auth.uid()) $$;

-- Client pemilik sebuah cabang.
CREATE OR REPLACE FUNCTION public.tenant_client(p_tenant text) RETURNS text
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$ SELECT t.client_id FROM public.tenants t WHERE t.id = p_tenant $$;

-- Client asal pengguna yang login (profil -> cabang -> client).
CREATE OR REPLACE FUNCTION public.app_client_id() RETURNS text
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$ SELECT t.client_id FROM public.profiles p JOIN public.tenants t ON t.id = p.tenant_id WHERE p.id = auth.uid() $$;

-- Apakah client pemilik cabang ini punya langganan yang masih berlaku?
CREATE OR REPLACE FUNCTION public.client_active_of_tenant(p_tenant text) RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.subscriptions s
     WHERE s.client_id = public.tenant_client(p_tenant)
       AND s.status IN ('trial', 'aktif')
       AND s.expires_at >= (now() AT TIME ZONE 'Asia/Jakarta')::date
  )
$$;

-- SATU-SATUNYA penentu akses data cabang (dipakai RLS + checkout()/process_return() POS).
--   superadmin   -> semua cabang
--   admin client -> semua cabang MILIK CLIENTNYA SAJA (ini perbaikan kebocoran antar client)
--   kasir        -> hanya cabang tempat ia bertugas
-- Perilaku admin pada data lama TIDAK berubah karena semua cabang lama ada di C0001.
CREATE OR REPLACE FUNCTION public.can_access_tenant(t text) RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
  SELECT public.is_superadmin() OR COALESCE((
    SELECT p.tenant_id = t
        OR (p.role = 'admin' AND public.tenant_client(t) IS NOT NULL
            AND public.tenant_client(t) = public.app_client_id())
      FROM public.profiles p WHERE p.id = auth.uid()
  ), false)
$$;

-- Boleh MENULIS data cabang ini? Selain punya akses, langganan client harus masih berlaku.
-- Superadmin dikecualikan supaya Anda tetap bisa ikut memperbaiki data client yang jatuh tempo.
CREATE OR REPLACE FUNCTION public.can_write_tenant(t text) RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$ SELECT public.can_access_tenant(t) AND (public.is_superadmin() OR public.client_active_of_tenant(t)) $$;

-- ---------------------------------------------------------------------------
-- 9. Pencatat log (client TIDAK boleh memanggilnya langsung)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.audit_actor_name() RETURNS text
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$ SELECT COALESCE((SELECT p.name FROM public.profiles p WHERE p.id = auth.uid()), 'Sistem') $$;

CREATE OR REPLACE FUNCTION public.audit_actor_role() RETURNS text
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$ SELECT CASE WHEN public.is_superadmin() THEN 'superadmin'
                 ELSE COALESCE((SELECT p.role FROM public.profiles p WHERE p.id = auth.uid()), 'sistem') END $$;

-- Satu-satunya pintu masuk audit_logs.
CREATE OR REPLACE FUNCTION public.write_audit(
  p_action text, p_entity text, p_entity_id text,
  p_client text, p_tenant text, p_detail jsonb
) RETURNS void
  LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path = ''
AS $$
  INSERT INTO public.audit_logs (actor_id, actor_name, actor_role, client_id, tenant_id, action, entity, entity_id, detail)
  VALUES (auth.uid(), public.audit_actor_name(), public.audit_actor_role(),
          COALESCE(p_client, public.tenant_client(p_tenant)), p_tenant, p_action, p_entity, p_entity_id,
          COALESCE(p_detail, '{}'::jsonb))
$$;-- ---------------------------------------------------------------------------
-- 10. Fungsi trigger LOG BISNIS
--     Dipasang di database, jadi tidak bisa dilewati aplikasi: perubahan stok/harga
--     oleh kasir, akun dibuat/dihapus, penjualan, retur -- semuanya tercatat sendiri.
-- ---------------------------------------------------------------------------

-- Stok & harga (stock_items)
CREATE OR REPLACE FUNCTION public.audit_stock() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_detail jsonb;
  v_action text;
  v_tenant text := COALESCE(NEW.tenant_id, OLD.tenant_id);
  v_item   text := COALESCE(NEW.id, OLD.id);
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_action := 'stock.create';
    v_detail := jsonb_build_object('name', NEW.name, 'qty', NEW.qty, 'unit', NEW.unit, 'price', NEW.price, 'barcode', NEW.barcode);
  ELSIF TG_OP = 'UPDATE' THEN
    v_detail := jsonb_strip_nulls(jsonb_build_object(
      'name',    CASE WHEN NEW.name    IS DISTINCT FROM OLD.name    THEN jsonb_build_object('dari', OLD.name,    'jadi', NEW.name)    END,
      'qty',     CASE WHEN NEW.qty     IS DISTINCT FROM OLD.qty     THEN jsonb_build_object('dari', OLD.qty,     'jadi', NEW.qty)     END,
      'unit',    CASE WHEN NEW.unit    IS DISTINCT FROM OLD.unit    THEN jsonb_build_object('dari', OLD.unit,    'jadi', NEW.unit)    END,
      'price',   CASE WHEN NEW.price   IS DISTINCT FROM OLD.price   THEN jsonb_build_object('dari', OLD.price,   'jadi', NEW.price)   END,
      'barcode', CASE WHEN NEW.barcode IS DISTINCT FROM OLD.barcode THEN jsonb_build_object('dari', OLD.barcode, 'jadi', NEW.barcode) END
    ));
    -- Tidak ada perubahan berarti: jangan buat log (menghindari sampah di dashboard).
    IF v_detail = '{}'::jsonb THEN RETURN NEW; END IF;
    v_action := CASE WHEN (v_detail ? 'price') AND NOT (v_detail ? 'qty') THEN 'price.update' ELSE 'stock.update' END;
  ELSE
    v_action := 'stock.delete';
    v_detail := jsonb_build_object('name', OLD.name, 'qty', OLD.qty, 'unit', OLD.unit, 'price', OLD.price);
  END IF;

  PERFORM public.write_audit(v_action, 'stock_items', v_item, NULL, v_tenant, v_detail);
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;

-- Akun pengguna (profiles)
CREATE OR REPLACE FUNCTION public.audit_profile() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_action text;
  v_detail jsonb;
  v_user   uuid;
  v_tenant text;
  v_name   text;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_action := 'user.create'; v_user := NEW.id; v_tenant := NEW.tenant_id; v_name := NEW.username;
    v_detail := jsonb_build_object('username', NEW.username, 'name', NEW.name, 'role', NEW.role, 'tenant_id', NEW.tenant_id);
  ELSIF TG_OP = 'UPDATE' THEN
    v_action := 'user.update'; v_user := NEW.id; v_tenant := NEW.tenant_id; v_name := NEW.username;
    v_detail := jsonb_strip_nulls(jsonb_build_object(
      'role',      CASE WHEN NEW.role      IS DISTINCT FROM OLD.role      THEN jsonb_build_object('dari', OLD.role,      'jadi', NEW.role)      END,
      'tenant_id', CASE WHEN NEW.tenant_id IS DISTINCT FROM OLD.tenant_id THEN jsonb_build_object('dari', OLD.tenant_id, 'jadi', NEW.tenant_id) END,
      'name',      CASE WHEN NEW.name      IS DISTINCT FROM OLD.name      THEN jsonb_build_object('dari', OLD.name,      'jadi', NEW.name)      END
    ));
    IF v_detail = '{}'::jsonb THEN RETURN NEW; END IF;
  ELSE
    v_action := 'user.delete'; v_user := OLD.id; v_tenant := OLD.tenant_id; v_name := OLD.username;
    v_detail := jsonb_build_object('username', OLD.username, 'name', OLD.name, 'role', OLD.role, 'tenant_id', OLD.tenant_id);
  END IF;

  PERFORM public.write_audit(v_action, 'profiles', v_name, NULL, v_tenant, v_detail || jsonb_build_object('user_id', v_user));
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;

-- Penjualan (sales) dan retur (stock_returns): hanya INSERT yang dicatat (tabel ini append-only).
