  CASE WHEN s.expires_at IS NULL THEN NULL
       ELSE (s.expires_at - (now() AT TIME ZONE 'Asia/Jakarta')::date) END AS days_left,
  COALESCE((SELECT count(*) FROM public.sales sa JOIN public.tenants t ON t.id = sa.tenant_id
     WHERE t.client_id = c.id AND sa.at >= now() - interval '30 days'), 0) AS trx_30d,
  COALESCE((SELECT sum(sa.total) FROM public.sales sa JOIN public.tenants t ON t.id = sa.tenant_id
     WHERE t.client_id = c.id AND sa.at >= now() - interval '30 days'), 0) AS omzet_30d,
  COALESCE((SELECT count(*) FROM public.client_events e
     WHERE e.client_id = c.id AND e.at >= now() - interval '7 days'), 0) AS events_7d,
  COALESCE((SELECT count(*) FROM public.client_events e
     WHERE e.client_id = c.id AND e.level = 'error' AND e.at >= now() - interval '7 days'), 0) AS errors_7d,
  COALESCE((SELECT count(*) FROM public.audit_logs a
     WHERE a.client_id = c.id AND a.at >= now() - interval '7 days'), 0) AS logs_7d
FROM public.clients c
LEFT JOIN LATERAL (
  SELECT s2.* FROM public.subscriptions s2
   WHERE s2.client_id = c.id
   ORDER BY (s2.status IN ('trial', 'aktif')) DESC, s2.expires_at DESC
   LIMIT 1
) s ON true
LEFT JOIN public.plans pl ON pl.code = s.plan_code;

