-- ============================================================================
-- Klontonk Dashboard - SKEMA CONTROL PLANE (multi-tenant, 1 project Supabase)
-- ----------------------------------------------------------------------------
-- Cara pakai: Supabase -> SQL Editor -> tempel SELURUH berkas ini -> Run.
-- Aman diulang (idempoten): semua objek memakai IF NOT EXISTS / OR REPLACE /
-- DROP ... IF EXISTS, jadi boleh dijalankan berkali-kali.
--
-- PRASYARAT: db/schema.sql milik klontonk_pos SUDAH dijalankan (tabel tenants,
--   profiles, stock_items, sales, sale_lines, stock_returns harus ada).
--
-- YANG DITAMBAHKAN BERKAS INI:
--   1. clients        - pemilik langganan (pelanggan Anda). 1 client = banyak cabang.
--   2. tenants.client_id - cabang kini milik client (migrasi data otomatis).
--   3. plans          - daftar paket (harga + batas cabang/pengguna).
--   4. subscriptions  - langganan per client (trial/aktif/jatuh tempo).
--   5. platform_admins- akun Anda (vendor), terpisah dari admin client.
--   6. audit_logs     - LOG BISNIS append-only, diisi trigger; client tidak bisa menghapus.
--   7. client_events  - LOG TEKNIS dari aplikasi POS di client (error/gagal simpan).
--   8. Hardening RLS  - can_access_tenant() dikunci ke client_id sehingga admin client A
--                       TIDAK bisa membaca/menghapus data client B.
--   9. Gate langganan - menulis data POS diblokir bila langganan client berakhir.
--
-- CATATAN KEAMANAN
--   * Tidak ada kunci service_role di berkas ini maupun di aplikasi. Keamanan = RLS.
--   * platform_admins TIDAK punya policy INSERT/UPDATE/DELETE: tidak ada yang bisa
--     mempromosikan dirinya jadi superadmin lewat API. Hanya lewat SQL Editor.
--   * audit_logs append-only: hak INSERT/UPDATE/DELETE DICABUT dari authenticated.
--   * Satu fungsi milik klontonk_pos DIGANTI (delete_app_user): versi di bawah ini
--     menambahkan batas client. Selengkapnya lihat komentar bagian 10.
-- ============================================================================

