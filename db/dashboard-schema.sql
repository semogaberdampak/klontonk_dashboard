  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 1. clients - pemilik langganan
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.clients (
  id            text PRIMARY KEY CHECK (id ~ '^C[0-9]{4}$'),
  name          text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 2 AND 80),
  contact_name  text CHECK (contact_name IS NULL OR char_length(btrim(contact_name)) <= 60),
  contact_phone text CHECK (contact_phone IS NULL OR contact_phone ~ '^[0-9+ -]{6,24}$'),
  contact_email text CHECK (contact_email IS NULL OR contact_email ~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'),
  note          text CHECK (note IS NULL OR char_length(note) <= 200),
  status        text NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','suspend','berhenti')),
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE SEQUENCE IF NOT EXISTS public.clients_id_seq AS bigint;

CREATE OR REPLACE FUNCTION public.gen_client_id() RETURNS text
  LANGUAGE plpgsql VOLATILE SET search_path = ''
AS $$
DECLARE
  v_next bigint := nextval('public.clients_id_seq');
BEGIN
  IF v_next > 9999 THEN
    RAISE EXCEPTION 'Batas 9999 client (format id C####) tercapai.' USING ERRCODE = 'P0001';
  END IF;
  RETURN 'C' || lpad(v_next::text, 4, '0');
END $$;

ALTER TABLE public.clients ALTER COLUMN id SET DEFAULT public.gen_client_id();

-- ---------------------------------------------------------------------------
-- 2. plans - daftar paket langganan
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.plans (
  code         text PRIMARY KEY CHECK (code ~ '^[a-z0-9_]{2,20}$'),
  name         text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 2 AND 40),
  price_month  integer NOT NULL DEFAULT 0 CHECK (price_month BETWEEN 0 AND 100000000),
  max_branches integer NOT NULL DEFAULT 1 CHECK (max_branches BETWEEN 1 AND 999),
  max_users    integer NOT NULL DEFAULT 3 CHECK (max_users BETWEEN 1 AND 999),
  is_active    boolean NOT NULL DEFAULT true,
  note         text CHECK (note IS NULL OR char_length(note) <= 200)
);

-- ---------------------------------------------------------------------------
-- 3. subscriptions - langganan per client
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.subscriptions (
