-- Ringkasan pemakaian harian satu client (halaman Pemakaian).
CREATE OR REPLACE FUNCTION public.usage_daily(p_client text, p_from date, p_to date)
RETURNS TABLE (
  day date, trx_count bigint, trx_total bigint,
  return_count bigint, return_amount bigint,
  event_count bigint, log_count bigint
)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_from date := COALESCE(p_from, (now() AT TIME ZONE 'Asia/Jakarta')::date - 29);
  v_to   date := COALESCE(p_to, (now() AT TIME ZONE 'Asia/Jakarta')::date);
BEGIN
  IF NOT (public.is_superadmin() OR p_client = public.app_client_id()) THEN
    RAISE EXCEPTION 'Akses ditolak.' USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  WITH t AS (SELECT tn.id FROM public.tenants tn WHERE tn.client_id = p_client),
       d AS (SELECT g::date AS d_day FROM generate_series(v_from, v_to, interval '1 day') g)
  SELECT d.d_day,
         (SELECT count(*) FROM public.sales s WHERE s.tenant_id IN (SELECT id FROM t)
            AND (s.at AT TIME ZONE 'Asia/Jakarta')::date = d.d_day)::bigint,
         (SELECT COALESCE(sum(s.total), 0) FROM public.sales s WHERE s.tenant_id IN (SELECT id FROM t)
            AND (s.at AT TIME ZONE 'Asia/Jakarta')::date = d.d_day)::bigint,
         (SELECT count(*) FROM public.stock_returns r WHERE r.tenant_id IN (SELECT id FROM t)
            AND (r.at AT TIME ZONE 'Asia/Jakarta')::date = d.d_day)::bigint,
         (SELECT COALESCE(sum(r.amount), 0) FROM public.stock_returns r WHERE r.tenant_id IN (SELECT id FROM t)
            AND (r.at AT TIME ZONE 'Asia/Jakarta')::date = d.d_day)::bigint,
         (SELECT count(*) FROM public.client_events e WHERE e.client_id = p_client
            AND (e.at AT TIME ZONE 'Asia/Jakarta')::date = d.d_day)::bigint,
         (SELECT count(*) FROM public.audit_logs a WHERE a.client_id = p_client
            AND (a.at AT TIME ZONE 'Asia/Jakarta')::date = d.d_day)::bigint
    FROM d
   ORDER BY d.d_day;
END $$;

-- Pemangkas log (Free plan hanya 500 MB). Retensi minimal 30 hari audit / 7 hari log teknis.
CREATE OR REPLACE FUNCTION public.purge_old_logs(p_audit_days integer DEFAULT 180, p_event_days integer DEFAULT 60)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_audit  bigint := 0;
  v_events bigint := 0;
BEGIN
  IF NOT public.is_superadmin() THEN
    RAISE EXCEPTION 'Akses ditolak. Fitur ini hanya untuk admin platform.' USING ERRCODE = '42501';
  END IF;
  IF p_audit_days IS NULL OR p_event_days IS NULL OR p_audit_days < 30 OR p_event_days < 7 THEN
    RAISE EXCEPTION 'Retensi minimal 30 hari (log audit) dan 7 hari (log teknis).' USING ERRCODE = '22023';
  END IF;

  DELETE FROM public.audit_logs WHERE at < now() - make_interval(days => p_audit_days);
  GET DIAGNOSTICS v_audit = ROW_COUNT;
  DELETE FROM public.client_events WHERE at < now() - make_interval(days => p_event_days);
  GET DIAGNOSTICS v_events = ROW_COUNT;

  RETURN jsonb_build_object('audit_deleted', v_audit, 'events_deleted', v_events);
END $$;

