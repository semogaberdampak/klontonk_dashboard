-- 12. Batas paket: jumlah cabang & pengguna mengikuti tabel plans.
--     Paket bawaan "internal" punya batas 999, jadi tidak mengganggu data lama.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.check_plan_limit() RETURNS trigger
  LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_client text;
  v_plan   public.plans%ROWTYPE;
  v_count  bigint;
BEGIN
  IF TG_TABLE_NAME = 'tenants' THEN
    v_client := NEW.client_id;
  ELSE
    v_client := public.tenant_client(NEW.tenant_id);
  END IF;

  SELECT p.* INTO v_plan
    FROM public.subscriptions s JOIN public.plans p ON p.code = s.plan_code
   WHERE s.client_id = v_client AND s.status IN ('trial','aktif')
     AND s.expires_at >= (now() AT TIME ZONE 'Asia/Jakarta')::date
   ORDER BY s.expires_at DESC LIMIT 1;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Client ini belum punya langganan aktif. Aktifkan langganan lebih dulu.' USING ERRCODE = 'P0001';
  END IF;

  IF TG_TABLE_NAME = 'tenants' THEN
    SELECT count(*) INTO v_count FROM public.tenants t WHERE t.client_id = v_client;
    IF v_count >= v_plan.max_branches THEN
      RAISE EXCEPTION 'Paket "%" hanya mengizinkan % cabang.', v_plan.name, v_plan.max_branches USING ERRCODE = 'P0001';
    END IF;
  ELSE
    SELECT count(*) INTO v_count
      FROM public.profiles p JOIN public.tenants t ON t.id = p.tenant_id
     WHERE t.client_id = v_client;
    IF v_count >= v_plan.max_users THEN
      RAISE EXCEPTION 'Paket "%" hanya mengizinkan % pengguna.', v_plan.name, v_plan.max_users USING ERRCODE = 'P0001';
    END IF;
  END IF;

  RETURN NEW;
END $$;

